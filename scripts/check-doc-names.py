#!/usr/bin/env python3
"""Fail when a wireframe or guide names Rust items or files that do not exist,
or when a wireframe leaves out part of its crate's public API.

For crates/*/WIREFRAME.md and docs/*.md, outside fenced example code:

- every multi-hump CamelCase name in inline code (`ScoreDirector`,
  `BiFilter<T>`, `a::ScoreDirector`) must be
  defined in crates/*/src (struct, enum, trait, type, union, enum variant, or
  a `use` item) or be a standard-library name;
- every `name(...)` call in inline code must name an identifier that occurs
  in crates/*/src (functions generated by macros count).

For each wireframe's file map (the `├──` / `└──` tree):

- every listed `.rs` / `.md` / `.txt` / `.toml` path must exist under the
  crate or its `src/`;
- every multi-hump CamelCase name in a file-map description must be
  defined, as above.

For each crate with a public-api.txt snapshot, every public struct, enum,
trait, function, type alias and macro in it must be named in the crate's
WIREFRAME.md.

Example code belongs in fenced blocks, which are not checked. Run from the
repository root; prints each problem with its location and exits 1 if any.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
# CamelCase: an upper-case letter followed by a lower-case one, so constants
# such as `ZERO` are not taken for types.
NAME = r"[A-Z][a-z][A-Za-z0-9]*"
# A checked type name has at least two humps (`ScoreDirector`, `BiFilter`):
# one-hump words are too often prose (`Tests`) or generic parameters (`Fa`).
CHECKED = r"\b[A-Z][a-z0-9]+[A-Z][A-Za-z0-9]*\b"
KEYWORDS = {"fn", "if", "impl", "for", "while", "match", "return", "where", "as", "in"}
STD_NAMES = {
    "Add", "Arc", "AsRef", "IntoIterator", "NaN", "Box", "Clone", "Copy", "Cow", "Debug", "Default", "Deserialize",
    "Display", "Drop", "Duration", "Eq", "Err", "Error", "Fn", "FnMut", "FnOnce",
    "Hash", "HashMap", "HashSet", "Instant", "Iterator", "Mul", "Neg", "None", "Ok",
    "Option", "Ord", "PartialEq", "PartialOrd", "PhantomData", "Rc", "Result", "Self",
    "Send", "Serialize", "Some", "String", "Sub", "Sync", "Vec",
}
TREE = re.compile(r"^((?:[│| ]   )*)[├└]── (\S+)(.*)$")
CALL = re.compile(r"(?<![A-Za-z0-9_])([a-z_][a-z0-9_]*)\(")
INLINE = re.compile(r"`([^`\n]+)`")


def source_texts():
    return [p.read_text(encoding="utf-8") for p in ROOT.glob("crates/*/src/**/*.rs")]


def defined_names(texts):
    item = re.compile(rf"\b(?:struct|enum|trait|type|union)\s+({NAME})\b")
    variant = re.compile(rf"^\s+({NAME})\s*[({{,=]", re.MULTILINE)
    use = re.compile(r"\buse\s[^;]*;")
    names = set(STD_NAMES)
    for text in texts:
        names.update(item.findall(text))
        names.update(variant.findall(text))
        for statement in use.findall(text):
            names.update(re.findall(NAME, statement))
    return names


def identifiers(texts):
    """Every identifier in the sources, so functions generated by macros count."""
    names = set()
    for text in texts:
        names.update(re.findall(r"\b[a-z_][a-z0-9_]*\b", text))
    return names


def prose_lines(path):
    """Yields (line number, line) outside fenced code blocks."""
    fenced = False
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if not fenced:
            yield number, line


def check_inline(path, types, functions, problems):
    for number, line in prose_lines(path):
        if TREE.match(line):
            continue
        for code in INLINE.findall(line):
            if code.startswith("#[") or "=" in code and "->" not in code:
                # Attributes and TOML/config snippets are not Rust item paths.
                continue
            for name in re.findall(CHECKED, code):
                if name not in types:
                    problems.append(f"{path.relative_to(ROOT)}:{number}: type `{name}`")
            for name in CALL.findall(code):
                if name not in functions and name not in KEYWORDS:
                    problems.append(f"{path.relative_to(ROOT)}:{number}: function `{name}`")


def check_file_map(path, types, problems):
    crate = path.parent
    stack = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        tree = TREE.match(line)
        if not tree:
            continue
        depth = len(tree.group(1)) // 4
        entry = tree.group(2)
        stack = stack[:depth] + [entry.rstrip("/")]
        for name in re.findall(CHECKED, tree.group(3)):
            if name not in types:
                problems.append(f"{path.relative_to(ROOT)}:{number}: type `{name}` in file map")
        if entry.endswith("/") or any(c in entry for c in "*{"):
            continue
        if not entry.endswith((".rs", ".md", ".txt", ".toml")):
            continue
        # A child of `module.rs` is listed by its path under `module/`.
        parents = [part for part in stack[:-1] if part != "src" and not part.endswith(".rs")]
        relative = "/".join(parents + [entry])
        if not any((base / relative).exists() for base in (crate, crate / "src")):
            problems.append(f"{path.relative_to(ROOT)}:{number}: file `{relative}` does not exist")


def check_public_api(path, problems):
    snapshot = path.parent / "public-api.txt"
    if not snapshot.exists():
        return
    wireframe = path.read_text(encoding="utf-8")
    item = re.compile(r"^(?:struct|enum|trait|fn|type|macro) ([\w:]+):")
    for line in snapshot.read_text(encoding="utf-8").splitlines():
        found = item.match(line)
        if not found:
            continue
        name = found.group(1).split("::")[-1]
        if not re.search(rf"\b{re.escape(name)}\b", wireframe):
            problems.append(
                f"{path.relative_to(ROOT)}: public item `{found.group(1)}` is not documented"
            )


def main():
    texts = source_texts()
    types = defined_names(texts)
    functions = identifiers(texts)
    problems = []
    for path in sorted(ROOT.glob("crates/*/WIREFRAME.md")):
        check_inline(path, types, functions, problems)
        check_file_map(path, types, problems)
        check_public_api(path, problems)
    for path in sorted(ROOT.glob("docs/*.md")):
        check_inline(path, types, functions, problems)
    if problems:
        print("Documentation names items or files that do not exist, or omits public items:")
        print("\n".join(problems))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
